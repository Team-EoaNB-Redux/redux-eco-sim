#!/usr/bin/env python
"""Writes data/game_effects.txt and data/game_triggers.txt: every effect and trigger the game's own documentation lists.

The simulator reads them to tell a real HOI4 effect it doesn't implement from a name the game rejects at load. A load
error zeroes every later math expression in its file (Interp::find_load_errors, docs/SEMANTICS.md). Rerun after a
game update.

  python tools/gen_game_names.py
  python tools/gen_game_names.py --docs "D:/Steam/steamapps/common/Hearts of Iron IV/documentation"
"""
import argparse
import re
from pathlib import Path

SIM = Path(__file__).resolve().parent.parent
DEFAULT_DOCS = Path("C:/Program Files (x86)/Steam/steamapps/common/Hearts of Iron IV/documentation")


def names(doc: Path) -> list[str]:
    # The table of contents lists each name once per scope: "* [name](#anchor)". Scope headings are upper case
    found = set(re.findall(r"^\* \[([A-Za-z_][\w@:.]*)\]\(#", doc.read_text(encoding="utf-8"), flags=re.M))
    return sorted(n for n in found if not n.isupper())


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--docs", type=Path, default=DEFAULT_DOCS, help="the game's documentation folder")
    args = ap.parse_args()
    out = SIM / "data"
    out.mkdir(exist_ok=True)
    for doc, target in (("effects_documentation.md", "game_effects.txt"), ("triggers_documentation.md", "game_triggers.txt")):
        found = names(args.docs / doc)
        header = f"# Generated by tools/gen_game_names.py from the game's {doc}. Don't edit by hand\n"
        (out / target).write_text(header + "\n".join(found) + "\n", encoding="utf-8")
        print(f"{target}: {len(found)} names")


if __name__ == "__main__":
    main()
